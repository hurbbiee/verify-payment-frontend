const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
// Platform environment variables take priority over the local .env file.
const configuredUrl = process.env.API_BASE_URL;
if (fs.existsSync(envPath)) process.loadEnvFile(envPath);
const raw = configuredUrl ?? process.env.API_BASE_URL;
if (!raw?.trim()) throw new Error('Set API_BASE_URL in frontend/.env or the build environment');
const apiBaseUrl = raw.trim().replace(/\/+$/, '');
const url = new URL(apiBaseUrl);
if (
  !['http:', 'https:'].includes(url.protocol) ||
  url.username ||
  url.password ||
  url.search ||
  url.hash
) {
  throw new Error('API_BASE_URL must be an HTTP(S) URL without credentials, query or fragment');
}
// Export ONLY this public URL. Never serialize process.env into frontend code.
fs.mkdirSync(path.join(root, 'src/app/core/config'), { recursive: true });
fs.writeFileSync(
  path.join(root, 'src/app/core/config/api.config.ts'),
  '// Generated by scripts/configure-api.cjs; configure API_BASE_URL instead.\n' +
    'export const API_BASE_URL: string = ' +
    JSON.stringify(apiBaseUrl) +
    ';\n',
);
console.log('Angular API URL configured');
